#!/usr/bin/env bash
set -euo pipefail

# F-1 for the recovered-device enrollment executor: each `EnrollDeviceIo`
# method's observation is the truth about the database and the grant store.
#
# `src/redemption_store.rs` splits every `EnrollDeviceIo` method in
# `vela-server/src/recovery/enroll_device.rs` into a typed statement plan
# (`plan_*`), the SQL/bytes it renders to (pinned byte for byte by its unit
# tests) and an observation classifier (`classify_*`). hax extracts the plans
# and classifiers here. `Vela_recovery_policy_redemption_model` models the
# `users`/`devices` tables and the enrollment-grant key-value store with a
# failure at any statement; `Vela_recovery_policy_redemption_lemmas` proves,
# for every starting state and every fault point, that each observation
# reports exactly what the run did and the store facts the redemption driver
# relies on.
#
# The driver and root modules come from `extraction-driver` (regenerated by
# verify-fstar-driver.sh, which runs first in verify-fstar.sh); this
# extraction keeps only the redemption-store module.

proof_root=$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)
cd "$proof_root"

for command_name in cargo cargo-hax driver-hax-frontend-exporter hax-engine fstar.exe z3-4.13.3 jq; do
  command -v "$command_name" >/dev/null || {
    echo "$command_name is missing; follow README.md" >&2
    exit 1
  }
done

[[ $(fstar.exe --version | head -n1) == 'F* 2025.10.06' ]] || {
  echo 'unexpected F* version' >&2
  exit 2
}
[[ -f proofs/fstar/extraction-driver/Vela_recovery_policy.Driver.fst ]] || {
  echo 'run verify-fstar-driver.sh first' >&2
  exit 1
}

# Rendering pins and the Rust mirror's shared vectors.
cargo test --lib redemption

items=(
  plan_take_grant plan_insert_device plan_authority_read plan_restore_grant
  classify_take classify_insert classify_authority
)
include='-**'
for item in "${items[@]}"; do
  include+=" +vela_recovery_policy::redemption_store::$item"
done

rm -rf proofs/fstar/extraction-redemption
cargo hax into \
  --output-dir proofs/fstar/extraction-redemption \
  -i "$include" \
  fstar --z3rlimit 500
# The partial driver and root modules hax writes alongside are superseded by
# the full driver extraction.
rm -f proofs/fstar/extraction-redemption/Vela_recovery_policy.Driver.fst
rm -f proofs/fstar/extraction-redemption/Vela_recovery_policy.fst

generated=(proofs/fstar/extraction-redemption/Vela_recovery_policy.Redemption_store.fst)
driver=(proofs/fstar/extraction-driver/*.fst)
model=(proofs/fstar/redemption-lemmas/Vela_recovery_policy_redemption_model.fst)
lemmas=(proofs/fstar/redemption-lemmas/Vela_recovery_policy_redemption_lemmas.fst)
for f in "${generated[@]}" "${model[@]}" "${lemmas[@]}"; do
  [[ -f $f ]] || { echo "missing $f" >&2; exit 1; }
done

python3 "$proof_root/../../security/formal/check-driver-proof-sources.py" \
  --generated "${generated[@]}" "${driver[@]}" \
  --proof "${model[@]}" "${lemmas[@]}" \
  --include-dir "$proof_root"

hax_lib_root=$(
  cargo metadata --format-version 1 |
    jq -r '.packages[] | select(.name == "hax-lib") | .manifest_path | sub("/Cargo.toml$"; "")'
)
[[ -n $hax_lib_root && -d $hax_lib_root ]] || {
  echo "could not locate hax-lib proof libraries" >&2
  exit 1
}

fstar_args=(
  --cmi
  --cache_off
  --warn_error -331
  --z3rlimit 200
  --z3version 4.13.3
  --already_cached '+Prims+FStar+LowStar+C+Spec.Loops+TestLib'
  --include "$hax_lib_root/proof-libs/fstar/core"
  --include "$hax_lib_root/proof-libs/fstar/rust_primitives"
  --include "$hax_lib_root/proofs/fstar/extraction"
  --include proofs/fstar/extraction-driver
  --include proofs/fstar/extraction-redemption
  --include proofs/fstar/redemption-lemmas
)
# One module at a time, each in its own process, so each stays within its
# memory budget.
for module in "${generated[@]}" "${model[@]}" "${lemmas[@]}"; do
  echo "checking $module"
  if [[ -x /usr/bin/time ]]; then
    /usr/bin/time -f "$module: %M KB peak, %e s" fstar.exe "${fstar_args[@]}" "$module"
  else
    fstar.exe "${fstar_args[@]}" "$module"
  fi
done

# Each mutant of the plans and classifiers must break the proof.
"$proof_root/verify-fstar-recovery-executors-mutations.sh"

echo "recovery executors: for every starting database, every starting grant and every failing statement, each enrollment executor's observation reports exactly what its statements did to users, devices and the grant store, and a failed run changes nothing"
sha256sum "${generated[@]}" "${model[@]}" "${lemmas[@]}" src/redemption_store.rs src/redemption_model.rs
