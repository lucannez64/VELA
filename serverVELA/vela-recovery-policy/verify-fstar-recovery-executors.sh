#!/usr/bin/env bash
set -euo pipefail

# F-1 for the recovered-device enrollment executor: each `EnrollDeviceIo`
# method's observation is the truth about the database and the grant store.
#
# `src/redemption_store.rs` splits every `EnrollDeviceIo` method in
# `vela-server/src/recovery/enroll_device.rs` into a typed statement plan
# (`plan_*`), the SQL/bytes it renders to (pinned byte for byte by its unit
# tests) and an observation classifier (`classify_*`). hax extracts the plans
# and classifiers here. `Vela_recovery_policy_redemption_model` models the
# `users`/`devices` tables and the enrollment-grant key-value store with a
# failure at any statement; `Vela_recovery_policy_redemption_lemmas` proves,
# for every starting state and every fault point, that each observation
# reports exactly what the run did and the store facts the redemption driver
# relies on.
#
# The WebAuthn recovery executors (`src/webauthn_store.rs`) are checked the
# same way against a model of the `users` row, the single-use attempt and
# registration slots, the credential-id index and the grant store
# (`proofs/fstar/webauthn-lemmas`), for every starting state, every ceremony
# result and every fault point.
#
# The driver and root modules come from `extraction-driver` (regenerated by
# verify-fstar-driver.sh, which runs first in verify-fstar.sh); this
# extraction keeps only the redemption-store module.

proof_root=$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)
cd "$proof_root"

for command_name in cargo cargo-hax driver-hax-frontend-exporter hax-engine fstar.exe z3-4.13.3 jq; do
  command -v "$command_name" >/dev/null || {
    echo "$command_name is missing; follow README.md" >&2
    exit 1
  }
done

[[ $(fstar.exe --version | head -n1) == 'F* 2025.10.06' ]] || {
  echo 'unexpected F* version' >&2
  exit 2
}
[[ -f proofs/fstar/extraction-driver/Vela_recovery_policy.Driver.fst ]] || {
  echo 'run verify-fstar-driver.sh first' >&2
  exit 1
}

# Rendering pins and the Rust mirror's shared vectors.
cargo test --lib

items=(
  plan_take_grant plan_insert_device plan_authority_read plan_restore_grant
  classify_take classify_insert classify_authority
)
share_items=(
  plan_stage_share plan_promote_staged_split plan_delete_share
  plan_stage_account plan_finalize_account plan_read_share
  classify_stage_update classify_stage_account classify_finalize_update
  classify_finalize_account classify_delete_update classify_read_share
)
possession_items=(
  plan_initiate_account plan_proof_slot plan_store_challenge
  plan_take_attempt plan_proof_account plan_issue_grant
  classify_initiate initiate_epoch classify_store_challenge
  classify_attempt classify_proof_account classify_grant_store
)
webauthn_items=(
  plan_select_share plan_select_credential plan_auth_slot
  plan_store_auth_state plan_take_auth_state plan_finish_account
  plan_update_credential_if_current plan_credential_holders
  plan_persist_credential plan_store_registration_state
  plan_take_registration_state plan_store_credential_grant
  classify_auth_start classify_finish_context classify_store_auth_state
  classify_store_registration_state classify_take_auth_state
  classify_credential_update classify_finish_account finish_account_split
  classify_share_release classify_grant_store
  classify_registration_start classify_registration_state
  classify_uniqueness classify_persist_credential
)
include='-**'
for item in "${items[@]}"; do
  include+=" +vela_recovery_policy::redemption_store::$item"
done
share_include='-**'
for item in "${share_items[@]}"; do
  share_include+=" +vela_recovery_policy::share_store::$item"
done
possession_include='-**'
for item in "${possession_items[@]}"; do
  possession_include+=" +vela_recovery_policy::possession_store::$item"
done
webauthn_include='-**'
for item in "${webauthn_items[@]}"; do
  webauthn_include+=" +vela_recovery_policy::webauthn_store::$item"
done

rm -rf proofs/fstar/extraction-redemption proofs/fstar/extraction-share proofs/fstar/extraction-possession proofs/fstar/extraction-webauthn
cargo hax into \
  --output-dir proofs/fstar/extraction-redemption \
  -i "$include" \
  fstar --z3rlimit 500
cargo hax into \
  --output-dir proofs/fstar/extraction-share \
  -i "$share_include" \
  fstar --z3rlimit 500
cargo hax into \
  --output-dir proofs/fstar/extraction-possession \
  -i "$possession_include" \
  fstar --z3rlimit 500
cargo hax into \
  --output-dir proofs/fstar/extraction-webauthn \
  -i "$webauthn_include" \
  fstar --z3rlimit 500
# The partial driver and root modules hax writes alongside are superseded by
# the full driver extractions.
rm -f proofs/fstar/extraction-redemption/Vela_recovery_policy.Driver.fst
rm -f proofs/fstar/extraction-redemption/Vela_recovery_policy.Recovery_share_driver.fst
rm -f proofs/fstar/extraction-redemption/Vela_recovery_policy.fst
rm -f proofs/fstar/extraction-share/Vela_recovery_policy.Recovery_share_driver.fst
rm -f proofs/fstar/extraction-share/Vela_recovery_policy.fst
rm -f proofs/fstar/extraction-possession/Vela_recovery_policy.Possession_driver.fst
rm -f proofs/fstar/extraction-possession/Vela_recovery_policy.fst
rm -f proofs/fstar/extraction-webauthn/Vela_recovery_policy.Webauthn_driver.fst
rm -f proofs/fstar/extraction-webauthn/Vela_recovery_policy.fst

generated=(
  proofs/fstar/extraction-redemption/Vela_recovery_policy.Redemption_store.fst
  proofs/fstar/extraction-share/Vela_recovery_policy.Share_store.fst
  proofs/fstar/extraction-share/Vela_recovery_policy.Redemption_store.fst
  proofs/fstar/extraction-possession/Vela_recovery_policy.Possession_store.fst
  proofs/fstar/extraction-webauthn/Vela_recovery_policy.Webauthn_store.fst
  proofs/fstar/extraction-webauthn/Vela_recovery_policy.Redemption_store.fst
)
driver=(proofs/fstar/extraction-driver/*.fst proofs/fstar/extraction-recovery-share-driver/*.fst proofs/fstar/extraction-possession-driver/*.fst)
model=(
  proofs/fstar/redemption-lemmas/Vela_recovery_policy_redemption_model.fst
  proofs/fstar/share-lemmas/Vela_recovery_policy_share_model.fst
  proofs/fstar/possession-lemmas/Vela_recovery_policy_possession_model.fst
  proofs/fstar/webauthn-lemmas/Vela_recovery_policy_webauthn_model.fst
)
lemmas=(
  proofs/fstar/redemption-lemmas/Vela_recovery_policy_redemption_lemmas.fst
  proofs/fstar/share-lemmas/Vela_recovery_policy_share_lemmas.fst
  proofs/fstar/possession-lemmas/Vela_recovery_policy_possession_lemmas.fst
  proofs/fstar/webauthn-lemmas/Vela_recovery_policy_webauthn_lemmas.fst
)
for f in "${generated[@]}" "${model[@]}" "${lemmas[@]}"; do
  [[ -f $f ]] || { echo "missing $f" >&2; exit 1; }
done

python3 "$proof_root/../../security/formal/check-driver-proof-sources.py" \
  --generated "${generated[@]}" "${driver[@]}" \
  --proof "${model[@]}" "${lemmas[@]}" \
  --include-dir "$proof_root"

hax_lib_root=$(
  cargo metadata --format-version 1 |
    jq -r '.packages[] | select(.name == "hax-lib") | .manifest_path | sub("/Cargo.toml$"; "")'
)
[[ -n $hax_lib_root && -d $hax_lib_root ]] || {
  echo "could not locate hax-lib proof libraries" >&2
  exit 1
}

check_group() {
  local -a group=("$@")
  local -a fstar_args=(
    --cmi
    --cache_off
    --warn_error -331
    --z3rlimit 200
    --z3version 4.13.3
    --already_cached '+Prims+FStar+LowStar+C+Spec.Loops+TestLib'
    --include "$hax_lib_root/proof-libs/fstar/core"
    --include "$hax_lib_root/proof-libs/fstar/rust_primitives"
    --include "$hax_lib_root/proofs/fstar/extraction"
  )
  case "$1" in
    *Share_store*)
      fstar_args+=(--include proofs/fstar/extraction-recovery-share-driver
                   --include proofs/fstar/extraction-share
                   --include proofs/fstar/share-lemmas)
      ;;
    *Possession_store*)
      fstar_args+=(--include proofs/fstar/extraction-possession-driver
                   --include proofs/fstar/extraction-possession
                   --include proofs/fstar/possession-lemmas)
      ;;
    *Webauthn_store*)
      fstar_args+=(--include proofs/fstar/extraction-webauthn-driver
                   --include proofs/fstar/extraction-webauthn
                   --include proofs/fstar/webauthn-lemmas)
      ;;
    *)
      fstar_args+=(--include proofs/fstar/extraction-driver
                   --include proofs/fstar/extraction-redemption
                   --include proofs/fstar/redemption-lemmas)
      ;;
  esac
  for module in "${group[@]}"; do
    echo "checking $module"
    if [[ -x /usr/bin/time ]]; then
      /usr/bin/time -f "$module: %M KB peak, %e s" fstar.exe "${fstar_args[@]}" "$module"
    else
      fstar.exe "${fstar_args[@]}" "$module"
    fi
  done
}

# One module at a time, each in its own process, so each stays within its
# memory budget. The families need different partial roots, so they are
# checked in separate include groups.
check_group "${generated[0]}" "${model[0]}" "${lemmas[0]}"
check_group "${generated[1]}" "${generated[2]}" "${model[1]}" "${lemmas[1]}"
check_group "${generated[3]}" "${model[2]}" "${lemmas[2]}"
check_group "${generated[4]}" "${model[3]}" "${lemmas[3]}"

# Each mutant of the plans and classifiers must break the proof.
"$proof_root/verify-fstar-recovery-executors-mutations.sh"

echo "recovery executors: for every starting database, every starting grant, every starting attempt slot, every starting users row, every stored credential, every WebAuthn slot and every failing statement, each enrollment, recovery-share, possession and WebAuthn executor's observation reports exactly what its statements did, and a failed run changes nothing"
sha256sum "${generated[@]}" "${model[@]}" "${lemmas[@]}" src/redemption_store.rs src/share_store.rs src/possession_store.rs src/webauthn_store.rs src/redemption_model.rs
