#!/usr/bin/env bash
set -euo pipefail

# Handler-to-driver link for POST /recovery/enroll-device.
#
# `src/redemption_interpreter.rs` defines the `redemption_interpreter!` loop
# once. The server's handler expands it with `.await`; this crate expands it
# into the synchronous `run_redemption`, which hax extracts here. The lemma
# module proves, for every executor, that `run_redemption` calls exactly the
# executor method for the effect the driver just emitted, performs one
# restoration for `RestoreAndFail`, stops at the verdict (or at the effect that
# aborted) within its five-turn budget, and ends in `run_from_ready ready evs`
# for the observations returned, so the per-request redemption theorems hold
# for the handler.
#
# The driver module itself is taken from `extraction-driver` (regenerated by
# verify-fstar-driver.sh, which runs first); this extraction keeps only the
# interpreter module.

proof_root=$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)
cd "$proof_root"

for command_name in cargo cargo-hax driver-hax-frontend-exporter hax-engine fstar.exe z3-4.13.3 jq; do
  command -v "$command_name" >/dev/null || {
    echo "$command_name is missing; follow README.md" >&2
    exit 1
  }
done

[[ $(fstar.exe --version | head -n1) == 'F* 2025.10.06' ]] || {
  echo 'unexpected F* version' >&2
  exit 2
}
[[ -f proofs/fstar/extraction-driver/Vela_recovery_policy.Driver.fst ]] || {
  echo 'run verify-fstar-driver.sh first' >&2
  exit 1
}

cargo test --lib redemption_interpreter

rm -rf proofs/fstar/extraction-redemption-interpreter
cargo hax into \
  --output-dir proofs/fstar/extraction-redemption-interpreter \
  -i '-** +vela_recovery_policy::redemption_interpreter::** +vela_recovery_policy::driver::begin_redemption +vela_recovery_policy::driver::step' \
  fstar --z3rlimit 500
# The partial root and driver modules hax writes alongside are superseded by
# the full extraction-driver artifact.
rm -f proofs/fstar/extraction-redemption-interpreter/Vela_recovery_policy.fst
rm -f proofs/fstar/extraction-redemption-interpreter/Vela_recovery_policy.Driver.fst

generated=(proofs/fstar/extraction-redemption-interpreter/Vela_recovery_policy.Redemption_interpreter.fst)
driver=(proofs/fstar/extraction-driver/*.fst)
driver_lemmas=(proofs/fstar/driver-lemmas/Vela_recovery_policy_driver_lemmas.fst)
lemmas=(proofs/fstar/redemption-interpreter-lemmas/Vela_recovery_policy_redemption_interpreter_lemmas.fst)
for f in "${generated[@]}" "${lemmas[@]}"; do
  [[ -f $f ]] || { echo "missing $f" >&2; exit 1; }
done

python3 "$proof_root/../../security/formal/check-driver-proof-sources.py" \
  --generated "${generated[@]}" "${driver[@]}" \
  --proof "${driver_lemmas[@]}" "${lemmas[@]}" \
  --include-dir "$proof_root"

hax_lib_root=$(
  cargo metadata --format-version 1 |
    jq -r '.packages[] | select(.name == "hax-lib") | .manifest_path | sub("/Cargo.toml$"; "")'
)
[[ -n $hax_lib_root && -d $hax_lib_root ]] || {
  echo "could not locate hax-lib proof libraries" >&2
  exit 1
}

fstar_args=(
  --cmi
  --cache_off
  --warn_error -331
  --z3rlimit 8000
  --z3version 4.13.3
  --already_cached '+Prims+FStar+LowStar+C+Spec.Loops+TestLib'
  --include "$hax_lib_root/proof-libs/fstar/core"
  --include "$hax_lib_root/proof-libs/fstar/rust_primitives"
  --include "$hax_lib_root/proofs/fstar/extraction"
  --include proofs/fstar/extraction-driver
  --include proofs/fstar/driver-lemmas
  --include proofs/fstar/extraction-redemption-interpreter
  --include proofs/fstar/redemption-interpreter-lemmas
  "${generated[@]}" "${lemmas[@]}"
)
fstar.exe "${fstar_args[@]}"

echo "redemption interpreter: the handler's loop calls only the executor method for the driver's current effect, restores once for RestoreAndFail, stops at the verdict (or abort) within 5 turns, and ends in the driver state the per-request theorems cover"
sha256sum "${generated[@]}" "${lemmas[@]}" src/redemption_interpreter.rs
