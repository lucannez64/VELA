#!/usr/bin/env bash
set -euo pipefail

# Handler-to-driver link for `POST /device/enroll`.
#
# `src/enroll_interpreter.rs` defines the `enroll_interpreter!` loop once. The
# server's handler expands it with `.await`; this crate expands it into the
# synchronous `run_enroll`, which hax extracts here. The lemma module proves,
# for every executor, that `run_enroll` calls exactly the executor method for
# the effect the driver just emitted, stops at the verdict, reaches a verdict
# within its budget, and ends in the driver state the per-request enrollment
# theorems cover.
#
# The driver module itself is taken from `extraction-enroll-driver`
# (regenerated by verify-fstar-enroll-driver.sh, which runs first); this
# extraction keeps only the interpreter module.

proof_root=$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)
cd "$proof_root"

for command_name in cargo cargo-hax driver-hax-frontend-exporter hax-engine fstar.exe z3-4.13.3 jq; do
  command -v "$command_name" >/dev/null || {
    echo "$command_name is missing; follow README.md" >&2
    exit 1
  }
done

[[ $(fstar.exe --version | head -n1) == 'F* 2025.10.06' ]] || {
  echo 'unexpected F* version' >&2
  exit 2
}
[[ -f proofs/fstar/extraction-enroll-driver/Vela_enrollment_policy.Enroll_driver.fst ]] || {
  echo 'run verify-fstar-enroll-driver.sh first' >&2
  exit 1
}

cargo test --lib enroll_interpreter

rm -rf proofs/fstar/extraction-enroll-interpreter
cargo hax into \
  --output-dir proofs/fstar/extraction-enroll-interpreter \
  -i '-** +vela_enrollment_policy::enroll_interpreter::** +vela_enrollment_policy::enroll_driver::step' \
  fstar --z3rlimit 500
# The partial driver and root modules hax writes alongside are superseded by
# the full enrollment-driver extraction.
rm -f proofs/fstar/extraction-enroll-interpreter/Vela_enrollment_policy.Enroll_driver.fst
rm -f proofs/fstar/extraction-enroll-interpreter/Vela_enrollment_policy.fst

generated=(proofs/fstar/extraction-enroll-interpreter/Vela_enrollment_policy.Enroll_interpreter.fst)
driver=(proofs/fstar/extraction-enroll-driver/*.fst)
driver_lemmas=(proofs/fstar/enroll-driver-lemmas/Vela_enrollment_policy_enroll_driver_lemmas.fst)
lemmas=(proofs/fstar/enroll-interpreter-lemmas/Vela_enrollment_policy_enroll_interpreter_lemmas.fst)
for f in "${generated[@]}" "${lemmas[@]}"; do
  [[ -f $f ]] || { echo "missing $f" >&2; exit 1; }
done

python3 "$proof_root/../../security/formal/check-driver-proof-sources.py" \
  --generated "${generated[@]}" "${driver[@]}" \
  --proof "${driver_lemmas[@]}" "${lemmas[@]}" \
  --include-dir "$proof_root"

hax_lib_root=$(
  cargo metadata --format-version 1 |
    jq -r '.packages[] | select(.name == "hax-lib") | .manifest_path | sub("/Cargo.toml$"; "")'
)
[[ -n $hax_lib_root && -d $hax_lib_root ]] || {
  echo "could not locate hax-lib proof libraries" >&2
  exit 1
}

fstar_args=(
  --cmi
  --cache_off
  --warn_error -331
  --z3rlimit 8000
  --z3version 4.13.3
  --already_cached '+Prims+FStar+LowStar+C+Spec.Loops+TestLib'
  --include "$hax_lib_root/proof-libs/fstar/core"
  --include "$hax_lib_root/proof-libs/fstar/rust_primitives"
  --include "$hax_lib_root/proofs/fstar/extraction"
  --include proofs/fstar/extraction-enroll-driver
  --include proofs/fstar/enroll-driver-lemmas
  --include proofs/fstar/extraction-enroll-interpreter
  --include proofs/fstar/enroll-interpreter-lemmas
  "${generated[@]}" "${lemmas[@]}"
)
fstar.exe "${fstar_args[@]}"

echo "enrollment interpreter: the handler's loop calls only the executor method for the driver's current effect, stops at the verdict within 5 turns, and ends in the driver state the per-request enrollment theorems cover"
sha256sum "${generated[@]}" "${lemmas[@]}" src/enroll_interpreter.rs
