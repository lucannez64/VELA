#!/usr/bin/env bash
set -euo pipefail

# Handler-to-driver link for PUT and GET /vault/chunk.
#
# `src/vault_upload_interpreter.rs` defines the two loops once
# (`upload_interpreter!`, `read_interpreter!`). The server's handlers expand
# them with `.await`; this crate expands them into the synchronous `run_upload`
# and `run_read`, which hax extracts here. The lemma module proves, for every
# executor, that the loop calls exactly the executor method for the effect the
# driver just emitted, stops at the verdict, reaches a verdict within its
# budget, and ends in `run_from_request request evs` for the observations
# returned, so the per-request upload and read theorems hold for the handler.
#
# The driver module itself is taken from `extraction-vault-upload-driver`
# (regenerated by verify-fstar-vault-upload-driver.sh, which runs first); this
# extraction keeps only the interpreter module.

proof_root=$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)
cd "$proof_root"

for command_name in cargo cargo-hax driver-hax-frontend-exporter hax-engine fstar.exe z3-4.13.3 jq; do
  command -v "$command_name" >/dev/null || {
    echo "$command_name is missing; follow README.md" >&2
    exit 1
  }
done

[[ $(fstar.exe --version | head -n1) == 'F* 2025.10.06' ]] || {
  echo 'unexpected F* version' >&2
  exit 2
}
driver_module=proofs/fstar/extraction-vault-upload-driver/Vela_rekey_policy.Vault_upload_driver.fst
[[ -f $driver_module ]] || {
  echo 'run verify-fstar-vault-upload-driver.sh first' >&2
  exit 1
}

cargo test --lib vault_upload_interpreter

rm -rf proofs/fstar/extraction-vault-upload-interpreter
cargo hax into \
  --output-dir proofs/fstar/extraction-vault-upload-interpreter \
  -i '-** +vela_rekey_policy::vault_upload_interpreter::** +vela_rekey_policy::vault_upload_driver::begin_upload +vela_rekey_policy::vault_upload_driver::upload_step +vela_rekey_policy::vault_upload_driver::begin_read +vela_rekey_policy::vault_upload_driver::read_step' \
  fstar --z3rlimit 500
# The partial driver module hax writes alongside is superseded by the full one.
rm -f proofs/fstar/extraction-vault-upload-interpreter/Vela_rekey_policy.Vault_upload_driver.fst
rm -f proofs/fstar/extraction-vault-upload-interpreter/Vela_rekey_policy.fst

generated=(proofs/fstar/extraction-vault-upload-interpreter/Vela_rekey_policy.Vault_upload_interpreter.fst)
driver=("$driver_module")
driver_lemmas=(proofs/fstar/vault-upload-driver-lemmas/Vela_rekey_policy_vault_upload_driver_lemmas.fst)
lemmas=(proofs/fstar/vault-upload-interpreter-lemmas/Vela_rekey_policy_vault_upload_interpreter_lemmas.fst)
for f in "${generated[@]}" "${driver[@]}" "${driver_lemmas[@]}" "${lemmas[@]}"; do
  [[ -f $f ]] || { echo "missing $f" >&2; exit 1; }
done

python3 "$proof_root/../../security/formal/check-driver-proof-sources.py" \
  --generated "${generated[@]}" "${driver[@]}" \
  --proof "${driver_lemmas[@]}" "${lemmas[@]}" \
  --include-dir "$proof_root"

hax_lib_root=$(
  cargo metadata --format-version 1 |
    jq -r '.packages[] | select(.name == "hax-lib") | .manifest_path | sub("/Cargo.toml$"; "")'
)
[[ -n $hax_lib_root && -d $hax_lib_root ]] || {
  echo "could not locate hax-lib proof libraries" >&2
  exit 1
}

fstar_args=(
  --cmi
  --cache_off
  --warn_error -331
  --z3rlimit 16000
  --z3version 4.13.3
  --already_cached '+Prims+FStar+LowStar+C+Spec.Loops+TestLib'
  --include "$hax_lib_root/proof-libs/fstar/core"
  --include "$hax_lib_root/proof-libs/fstar/rust_primitives"
  --include "$hax_lib_root/proofs/fstar/extraction"
  --include proofs/fstar/extraction-vault-upload-driver-root
  --include proofs/fstar/extraction-vault-upload-driver
  --include proofs/fstar/vault-upload-driver-lemmas
  --include proofs/fstar/extraction-vault-upload-interpreter
  --include proofs/fstar/vault-upload-interpreter-lemmas
  "${driver[@]}" "${generated[@]}" "${driver_lemmas[@]}" "${lemmas[@]}"
)
printf 'F* vault-upload-interpreter argv:'
printf ' %q' "${fstar_args[@]}"
printf '\n'
fstar.exe "${fstar_args[@]}"

echo "vault upload interpreter: the handler's loops call only the executor method for the driver's current effect, stop at the verdict within 7 (upload) / 2 (read) turns, and end in the driver state the per-request theorems cover"
sha256sum "${generated[@]}" "${driver[@]}" "${lemmas[@]}" src/vault_upload_interpreter.rs
