#!/usr/bin/env bash
set -euo pipefail

# F-1 for the session executors: each executor method's observation is the
# truth about the database and store.
#
# `src/store.rs` splits every session executor method in
# `vela-server/src/{auth/logout.rs,device/revoke.rs,account/delete.rs}` into a
# typed statement plan (`plan_*`), the SQL/store rendering (pinned by its unit
# tests) and an observation classifier (`classify_*`). hax extracts the plans
# and classifiers here. `Vela_session_policy_store_model` models the eight
# tables and the store they touch, statement and transaction semantics and a
# failure at any statement; `Vela_session_policy_store_lemmas` proves, for
# every starting database and every fault point, that each observation reports
# exactly what the run did, and the facts the session drivers rely on.
#
# The deletion and revocation driver modules come from
# `extraction-deletion-driver` (regenerated by
# verify-fstar-deletion-driver.sh, which runs earlier in verify-fstar.sh); this
# extraction keeps only the store module.

proof_root=$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)
cd "$proof_root"

for command_name in cargo cargo-hax driver-hax-frontend-exporter hax-engine fstar.exe z3-4.13.3 jq; do
  command -v "$command_name" >/dev/null || {
    echo "$command_name is missing; follow README.md" >&2
    exit 1
  }
done

[[ $(fstar.exe --version | head -n1) == 'F* 2025.10.06' ]] || {
  echo 'unexpected F* version' >&2
  exit 2
}
[[ -f proofs/fstar/extraction-deletion-driver/Vela_session_policy.Deletion_driver.fst ]] || {
  echo 'run verify-fstar-deletion-driver.sh first' >&2
  exit 1
}
[[ -f proofs/fstar/extraction-revocation-driver/Vela_session_policy.Revocation_driver.fst ]] || {
  echo 'run verify-fstar-revocation-driver.sh first' >&2
  exit 1
}

# Rendering pins, classifier tables and the Rust mirror's shared vectors.
cargo test --lib store

items=(
  plan_logout plan_sentinel plan_lockout_device plan_lockout_web_session
  plan_scan_devices plan_scan_web_sessions plan_delete_table plan_delete_users
  plan_commit plan_target_lookup plan_revoke_record plan_cascade_read
  plan_cascade_update
  classify_logout classify_lockout_device classify_scan classify_lockout_ignored
  classify_transaction classify_table_delete classify_users_delete classify_commit
  classify_target classify_record classify_cascade
)
include='-**'
for item in "${items[@]}"; do
  include+=" +vela_session_policy::store::$item"
done

rm -rf proofs/fstar/extraction-store
cargo hax into \
  --output-dir proofs/fstar/extraction-store \
  -i "$include" \
  fstar --z3rlimit 500
# The partial driver and root modules hax writes alongside are superseded by
# the full driver extraction.
rm -f proofs/fstar/extraction-store/Vela_session_policy.Deletion_driver.fst
rm -f proofs/fstar/extraction-store/Vela_session_policy.Revocation_driver.fst
rm -f proofs/fstar/extraction-store/Vela_session_policy.fst

generated=(proofs/fstar/extraction-store/Vela_session_policy.Store.fst)
driver=(proofs/fstar/extraction-deletion-driver/*.fst)
model=(proofs/fstar/store-lemmas/Vela_session_policy_store_model.fst)
lemmas=(proofs/fstar/store-lemmas/Vela_session_policy_store_lemmas.fst)
for f in "${generated[@]}" "${model[@]}" "${lemmas[@]}"; do
  [[ -f $f ]] || { echo "missing $f" >&2; exit 1; }
done

python3 "$proof_root/../../security/formal/check-driver-proof-sources.py" \
  --generated "${generated[@]}" "${driver[@]}" \
  --proof "${model[@]}" "${lemmas[@]}" \
  --include-dir "$proof_root"

hax_lib_root=$(
  cargo metadata --format-version 1 |
    jq -r '.packages[] | select(.name == "hax-lib") | .manifest_path | sub("/Cargo.toml$"; "")'
)
[[ -n $hax_lib_root && -d $hax_lib_root ]] || {
  echo "could not locate hax-lib proof libraries" >&2
  exit 1
}

fstar_args=(
  --cmi
  --cache_off
  --warn_error -331
  --z3rlimit 200
  --z3version 4.13.3
  --already_cached '+Prims+FStar+LowStar+C+Spec.Loops+TestLib'
  --include "$hax_lib_root/proof-libs/fstar/core"
  --include "$hax_lib_root/proof-libs/fstar/rust_primitives"
  --include "$hax_lib_root/proofs/fstar/extraction"
  --include proofs/fstar/extraction
  --include proofs/fstar/extraction-deletion-driver
  --include proofs/fstar/extraction-revocation-driver
  --include proofs/fstar/extraction-store
  --include proofs/fstar/store-lemmas
)
# One module at a time, each in its own process, so each stays within its
# memory budget.
for module in "${generated[@]}" "${model[@]}" "${lemmas[@]}"; do
  echo "checking $module"
  if [[ -x /usr/bin/time ]]; then
    /usr/bin/time -f "$module: %M KB peak, %e s" fstar.exe "${fstar_args[@]}" "$module"
  else
    fstar.exe "${fstar_args[@]}" "$module"
  fi
done

# Each mutant of the plans and classifiers must break the proof.
"$proof_root/verify-fstar-session-executors-mutations.sh"

echo "session executors: for every starting database and store and every failing statement, the logout, device-revocation and account-deletion executors' observations report exactly what their statements did to the eight tables and the store keys, and a failed run leaves the transaction uncommitted"
sha256sum "${generated[@]}" "${model[@]}" "${lemmas[@]}" src/store.rs src/store_model.rs
