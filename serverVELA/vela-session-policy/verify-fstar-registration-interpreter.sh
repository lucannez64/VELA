#!/usr/bin/env bash
set -euo pipefail

# Handler-to-driver link for POST /account/register.
#
# `src/registration_interpreter.rs` defines the `registration_interpreter!` loop
# once. The server's handler expands it with `.await`; this crate expands it
# into the synchronous `run_registration`, which hax extracts here. The lemma
# module proves, for every executor, that `run_registration` calls exactly the
# executor method for the effect the driver just emitted, stops at the verdict,
# reaches a verdict within its eight-turn budget, and ends in
# `run_from_observation observation evs` for the observations returned, so the
# per-request registration theorems hold for the handler.
#
# The driver module itself is taken from `extraction-registration-driver`
# (regenerated by verify-fstar-registration-driver.sh, which runs first); this
# extraction keeps only the interpreter module.

proof_root=$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)
cd "$proof_root"

for command_name in cargo cargo-hax driver-hax-frontend-exporter hax-engine fstar.exe z3-4.13.3 jq; do
  command -v "$command_name" >/dev/null || {
    echo "$command_name is missing; follow README.md" >&2
    exit 1
  }
done

[[ $(fstar.exe --version | head -n1) == 'F* 2025.10.06' ]] || {
  echo 'unexpected F* version' >&2
  exit 2
}
[[ -f proofs/fstar/extraction-registration-driver/Vela_session_policy.Registration_driver.fst ]] || {
  echo 'run verify-fstar-registration-driver.sh first' >&2
  exit 1
}

cargo test --lib registration_interpreter

rm -rf proofs/fstar/extraction-registration-interpreter
cargo hax into \
  --output-dir proofs/fstar/extraction-registration-interpreter \
  -i '-** +vela_session_policy::registration_interpreter::** +vela_session_policy::registration_driver::begin_registration +vela_session_policy::registration_driver::step' \
  fstar --z3rlimit 500
# The partial driver module hax writes alongside is superseded by the full one.
rm -f proofs/fstar/extraction-registration-interpreter/Vela_session_policy.Registration_driver.fst

generated=(proofs/fstar/extraction-registration-interpreter/Vela_session_policy.Registration_interpreter.fst)
driver=(proofs/fstar/extraction-registration-driver/*.fst)
driver_lemmas=(proofs/fstar/registration-driver-lemmas/Vela_session_policy_registration_driver_lemmas.fst)
lemmas=(proofs/fstar/registration-interpreter-lemmas/Vela_session_policy_registration_interpreter_lemmas.fst)
for f in "${generated[@]}" "${lemmas[@]}"; do
  [[ -f $f ]] || { echo "missing $f" >&2; exit 1; }
done

python3 "$proof_root/../../security/formal/check-driver-proof-sources.py" \
  --generated "${generated[@]}" "${driver[@]}" \
  --proof "${driver_lemmas[@]}" "${lemmas[@]}" \
  --include-dir "$proof_root"

hax_lib_root=$(
  cargo metadata --format-version 1 |
    jq -r '.packages[] | select(.name == "hax-lib") | .manifest_path | sub("/Cargo.toml$"; "")'
)
[[ -n $hax_lib_root && -d $hax_lib_root ]] || {
  echo "could not locate hax-lib proof libraries" >&2
  exit 1
}

fstar_args=(
  --cmi
  --cache_off
  --warn_error -331
  --z3rlimit 8000
  --z3version 4.13.3
  --already_cached '+Prims+FStar+LowStar+C+Spec.Loops+TestLib'
  --include "$hax_lib_root/proof-libs/fstar/core"
  --include "$hax_lib_root/proof-libs/fstar/rust_primitives"
  --include "$hax_lib_root/proofs/fstar/extraction"
  --include proofs/fstar/extraction-registration-driver
  --include proofs/fstar/registration-driver-lemmas
  --include proofs/fstar/extraction-registration-interpreter
  --include proofs/fstar/registration-interpreter-lemmas
  "${generated[@]}" "${driver_lemmas[@]}" "${lemmas[@]}"
)
printf 'F* registration-interpreter argv:'
printf ' %q' "${fstar_args[@]}"
printf '\n'
fstar.exe "${fstar_args[@]}"

echo "registration interpreter: the handler's loop calls only the executor method for the driver's current effect, stops at the verdict within 8 turns, and ends in the driver state the per-request theorems cover"
sha256sum "${generated[@]}" "${lemmas[@]}" src/registration_interpreter.rs
