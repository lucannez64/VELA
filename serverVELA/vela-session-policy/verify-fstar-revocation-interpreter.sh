#!/usr/bin/env bash
set -euo pipefail

# Handler-to-driver link for POST /device/revoke and POST /auth/logout.
#
# `src/revocation_interpreter.rs` defines the `revocation_interpreter!` and
# `logout_interpreter!` loops once. The server's handlers expand them with
# `.await`; this crate expands them into the synchronous `run_revocation` and
# `run_logout`, which hax extracts here. The lemma module proves, for every
# executor, that each loop calls exactly the executor method for the effect the
# driver just emitted, stops at the verdict, reaches a verdict within its
# budget, and ends in the trace the per-request revocation/logout theorems
# cover.
#
# The driver module itself is taken from `extraction-revocation-driver`
# (regenerated by verify-fstar-revocation-driver.sh, which runs first); this
# extraction keeps only the interpreter module.

proof_root=$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)
cd "$proof_root"

for command_name in cargo cargo-hax driver-hax-frontend-exporter hax-engine fstar.exe z3-4.13.3 jq; do
  command -v "$command_name" >/dev/null || {
    echo "$command_name is missing; follow README.md" >&2
    exit 1
  }
done

[[ $(fstar.exe --version | head -n1) == 'F* 2025.10.06' ]] || {
  echo 'unexpected F* version' >&2
  exit 2
}
[[ -f proofs/fstar/extraction-revocation-driver/Vela_session_policy.Revocation_driver.fst ]] || {
  echo 'run verify-fstar-revocation-driver.sh first' >&2
  exit 1
}

cargo test --lib revocation_interpreter

rm -rf proofs/fstar/extraction-revocation-interpreter
cargo hax into \
  --output-dir proofs/fstar/extraction-revocation-interpreter \
  -i '-** +vela_session_policy::revocation_interpreter::** +vela_session_policy::revocation_driver::begin_revocation +vela_session_policy::revocation_driver::begin_logout +vela_session_policy::revocation_driver::step +vela_session_policy::revocation_driver::logout_step' \
  fstar --z3rlimit 500
# The partial driver module hax writes alongside is superseded by the full one.
rm -f proofs/fstar/extraction-revocation-interpreter/Vela_session_policy.Revocation_driver.fst

generated=(proofs/fstar/extraction-revocation-interpreter/Vela_session_policy.Revocation_interpreter.fst)
driver=(proofs/fstar/extraction-revocation-driver/*.fst)
driver_lemmas=(proofs/fstar/revocation-driver-lemmas/Vela_session_policy_revocation_driver_lemmas.fst)
lemmas=(proofs/fstar/revocation-interpreter-lemmas/Vela_session_policy_revocation_interpreter_lemmas.fst)
for f in "${generated[@]}" "${lemmas[@]}"; do
  [[ -f $f ]] || { echo "missing $f" >&2; exit 1; }
done

python3 "$proof_root/../../security/formal/check-driver-proof-sources.py" \
  --generated "${generated[@]}" "${driver[@]}" \
  --proof "${driver_lemmas[@]}" "${lemmas[@]}" \
  --include-dir "$proof_root"

hax_lib_root=$(
  cargo metadata --format-version 1 |
    jq -r '.packages[] | select(.name == "hax-lib") | .manifest_path | sub("/Cargo.toml$"; "")'
)
[[ -n $hax_lib_root && -d $hax_lib_root ]] || {
  echo "could not locate hax-lib proof libraries" >&2
  exit 1
}

fstar_args=(
  --cmi
  --cache_off
  --warn_error -331
  --z3rlimit 8000
  --z3version 4.13.3
  --already_cached '+Prims+FStar+LowStar+C+Spec.Loops+TestLib'
  --include "$hax_lib_root/proof-libs/fstar/core"
  --include "$hax_lib_root/proof-libs/fstar/rust_primitives"
  --include "$hax_lib_root/proofs/fstar/extraction"
  --include proofs/fstar/extraction-revocation-driver
  --include proofs/fstar/revocation-driver-lemmas
  --include proofs/fstar/extraction-revocation-interpreter
  --include proofs/fstar/revocation-interpreter-lemmas
  "${generated[@]}" "${lemmas[@]}"
)
fstar.exe "${fstar_args[@]}"

echo "revocation interpreter: the handler's loop calls only the executor method for the driver's current effect, stops at the verdict within 4 turns, and ends in the driver state the per-request revocation theorems cover"
echo "logout interpreter: exactly one JTI write, then the verdict, within 1 turn"
sha256sum "${generated[@]}" "${lemmas[@]}" src/revocation_interpreter.rs
