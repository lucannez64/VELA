#!/usr/bin/env bash
set -euo pipefail

# Handler-to-driver link for GET /auth/challenge.
#
# `src/challenge_issue_interpreter.rs` defines the `challenge_issue_interpreter!`
# loop once. The server's handler expands it with `.await`; this crate expands
# it into the synchronous `run_issue`, which hax extracts here. The lemma module
# proves, for every executor, that `run_issue` calls exactly the executor method
# for the effect the driver just emitted, stops at the verdict, reaches a
# verdict within its three-turn budget, and ends in `run_from_purpose purpose
# evs` for the observations returned, so the per-request issue theorems hold for
# the handler.
#
# The driver module itself is taken from `extraction-challenge-issue-driver`
# (regenerated by verify-fstar-challenge-issue-driver.sh, which runs first);
# this extraction keeps only the interpreter module.

proof_root=$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)
cd "$proof_root"

for command_name in cargo cargo-hax driver-hax-frontend-exporter hax-engine fstar.exe z3-4.13.3 jq; do
  command -v "$command_name" >/dev/null || {
    echo "$command_name is missing; follow README.md" >&2
    exit 1
  }
done

[[ $(fstar.exe --version | head -n1) == 'F* 2025.10.06' ]] || {
  echo 'unexpected F* version' >&2
  exit 2
}
[[ -f proofs/fstar/extraction-challenge-issue-driver/Vela_session_policy.Challenge_issue_driver.fst ]] || {
  echo 'run verify-fstar-challenge-issue-driver.sh first' >&2
  exit 1
}

cargo test --lib challenge_issue

rm -rf proofs/fstar/extraction-challenge-issue-interpreter
cargo hax into \
  --output-dir proofs/fstar/extraction-challenge-issue-interpreter \
  -i '-** +vela_session_policy::challenge_issue_interpreter::** +vela_session_policy::challenge_issue_driver::begin_issue +vela_session_policy::challenge_issue_driver::step +vela_session_policy::challenge_issue_driver::issue_stage_index' \
  fstar --z3rlimit 500
# The partial driver and challenge modules hax writes alongside are superseded
# by the full ones in `extraction-challenge-issue-driver`.
rm -f proofs/fstar/extraction-challenge-issue-interpreter/Vela_session_policy.Challenge_issue_driver.fst
rm -f proofs/fstar/extraction-challenge-issue-interpreter/Vela_session_policy.Challenge.fst

generated=(proofs/fstar/extraction-challenge-issue-interpreter/Vela_session_policy.Challenge_issue_interpreter.fst)
driver=(proofs/fstar/extraction-challenge-issue-driver/*.fst)
driver_lemmas=(proofs/fstar/challenge-issue-driver-lemmas/Vela_session_policy_challenge_issue_driver_lemmas.fst)
lemmas=(proofs/fstar/challenge-issue-interpreter-lemmas/Vela_session_policy_challenge_issue_interpreter_lemmas.fst)
for f in "${generated[@]}" "${lemmas[@]}"; do
  [[ -f $f ]] || { echo "missing $f" >&2; exit 1; }
done

python3 "$proof_root/../../security/formal/check-driver-proof-sources.py" \
  --generated "${generated[@]}" "${driver[@]}" \
  --proof "${driver_lemmas[@]}" "${lemmas[@]}" \
  --include-dir "$proof_root"

hax_lib_root=$(
  cargo metadata --format-version 1 |
    jq -r '.packages[] | select(.name == "hax-lib") | .manifest_path | sub("/Cargo.toml$"; "")'
)
[[ -n $hax_lib_root && -d $hax_lib_root ]] || {
  echo "could not locate hax-lib proof libraries" >&2
  exit 1
}

fstar_args=(
  --cmi
  --cache_off
  --warn_error -331
  --z3rlimit 8000
  --z3version 4.13.3
  --already_cached '+Prims+FStar+LowStar+C+Spec.Loops+TestLib'
  --include "$hax_lib_root/proof-libs/fstar/core"
  --include "$hax_lib_root/proof-libs/fstar/rust_primitives"
  --include "$hax_lib_root/proofs/fstar/extraction"
  --include proofs/fstar/extraction-challenge-issue-driver
  --include proofs/fstar/challenge-issue-driver-lemmas
  --include proofs/fstar/extraction-challenge-issue-interpreter
  --include proofs/fstar/challenge-issue-interpreter-lemmas
  "${generated[@]}" "${driver_lemmas[@]}" "${lemmas[@]}"
)
printf 'F* challenge-issue-interpreter argv:'
printf ' %q' "${fstar_args[@]}"
printf '\n'
fstar.exe "${fstar_args[@]}"

echo "challenge issue interpreter: the handler's loop calls only the executor method for the driver's current effect, stops at the verdict within 3 turns, and ends in the driver state the per-request theorems cover"
sha256sum "${generated[@]}" "${lemmas[@]}" src/challenge_issue_interpreter.rs
