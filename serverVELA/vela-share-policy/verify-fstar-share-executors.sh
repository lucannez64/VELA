#!/usr/bin/env bash
set -euo pipefail

# F-1 for the sharing executors: each executor method's observation is the
# truth about the database.
#
# `src/store.rs` splits every `impl ShareExecutor` method in
# `vela-server/src/share/mod.rs` into a typed statement plan (`plan_*`), the
# SQL rendering (pinned byte for byte by its unit tests) and an observation
# classifier (`classify_*`). hax extracts the plans and classifiers here.
# `Vela_share_policy_store_model` models the tables they touch, statement
# and transaction semantics and a failure at any statement;
# `Vela_share_policy_store_lemmas` proves, for every starting database and
# every fault point, that each observation reports exactly what the run did
# to the tables, and the store facts the sharing driver relies on.
#
# The driver and root modules come from `extraction-driver` (regenerated by
# verify-fstar-driver.sh, which runs first in verify-fstar.sh); this
# extraction keeps only the store module.

proof_root=$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)
cd "$proof_root"

for command_name in cargo cargo-hax driver-hax-frontend-exporter hax-engine fstar.exe z3-4.13.3 jq; do
  command -v "$command_name" >/dev/null || {
    echo "$command_name is missing; follow ../vela-rekey-policy/README.md" >&2
    exit 1
  }
done

[[ $(fstar.exe --version | head -n1) == 'F* 2025.10.06' ]] || {
  echo 'unexpected F* version' >&2
  exit 2
}
[[ -f proofs/fstar/extraction-driver/Vela_share_policy.Driver.fst ]] || {
  echo 'run verify-fstar-driver.sh first' >&2
  exit 1
}

# Rendering pins and the Rust mirror's shared vectors.
cargo test --lib store

items=(
  plan_send_insert plan_link_read plan_link_update plan_link_revoke
  plan_linked_inbox_cleanup plan_inbox_delete plan_device_read
  plan_share_ek_update classify_send classify_rows classify_cleanup
  classify_link classify_device
)
include='-**'
for item in "${items[@]}"; do
  include+=" +vela_share_policy::store::$item"
done

rm -rf proofs/fstar/extraction-store
cargo hax into \
  --output-dir proofs/fstar/extraction-store \
  -i "$include" \
  fstar --z3rlimit 500
# The partial driver and root modules hax writes alongside are superseded by
# the full driver extraction.
rm -f proofs/fstar/extraction-store/Vela_share_policy.Driver.fst
rm -f proofs/fstar/extraction-store/Vela_share_policy.fst

generated=(proofs/fstar/extraction-store/Vela_share_policy.Store.fst)
driver=(proofs/fstar/extraction-driver/*.fst)
model=(proofs/fstar/store-lemmas/Vela_share_policy_store_model.fst)
lemmas=(proofs/fstar/store-lemmas/Vela_share_policy_store_lemmas.fst)
for f in "${generated[@]}" "${model[@]}" "${lemmas[@]}"; do
  [[ -f $f ]] || { echo "missing $f" >&2; exit 1; }
done

python3 "$proof_root/../../security/formal/check-driver-proof-sources.py" \
  --generated "${generated[@]}" "${driver[@]}" \
  --proof "${model[@]}" "${lemmas[@]}" \
  --include-dir "$proof_root"

hax_lib_root=$(
  cargo metadata --format-version 1 |
    jq -r '.packages[] | select(.name == "hax-lib") | .manifest_path | sub("/Cargo.toml$"; "")'
)
[[ -n $hax_lib_root && -d $hax_lib_root ]] || {
  echo "could not locate hax-lib proof libraries" >&2
  exit 1
}

fstar_args=(
  --cmi
  --cache_off
  --warn_error -331
  --z3rlimit 200
  --z3version 4.13.3
  --already_cached '+Prims+FStar+LowStar+C+Spec.Loops+TestLib'
  --include "$hax_lib_root/proof-libs/fstar/core"
  --include "$hax_lib_root/proof-libs/fstar/rust_primitives"
  --include "$hax_lib_root/proofs/fstar/extraction"
  --include proofs/fstar/extraction-driver
  --include proofs/fstar/extraction-store
  --include proofs/fstar/store-lemmas
)
# One module at a time, each in its own process, so each stays within its
# memory budget.
for module in "${generated[@]}" "${model[@]}" "${lemmas[@]}"; do
  echo "checking $module"
  if [[ -x /usr/bin/time ]]; then
    /usr/bin/time -f "$module: %M KB peak, %e s" fstar.exe "${fstar_args[@]}" "$module"
  else
    fstar.exe "${fstar_args[@]}" "$module"
  fi
done

# Each mutant of the plans and classifiers must break the proof.
"$proof_root/verify-fstar-share-executors-mutations.sh"

echo "share executors: for every starting database and every failing statement, each sharing executor's observation reports exactly what its statements did to shared_items, share_inbox and users, and a failed run leaves the tables unchanged"
sha256sum "${generated[@]}" "${model[@]}" "${lemmas[@]}" src/store.rs src/store_model.rs
