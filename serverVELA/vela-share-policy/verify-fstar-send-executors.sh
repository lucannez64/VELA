#!/usr/bin/env bash
set -euo pipefail

# F-1 for the one-off share-link executors: each executor method's observation
# is the truth about the `sends` table.
#
# `src/store.rs` splits every executor method in `vela-server/src/send.rs`
# (`CreateSendIo`, `FetchSendIo`, `DeleteSendIo`) into a typed statement plan
# (`plan_send_*`), the SQL rendering (pinned byte for byte by its unit tests)
# and an observation classifier (`classify_send_*`). hax extracts the plans and
# classifiers into the same `Vela_share_policy.Store` module the sharing
# executors use; `Vela_share_policy_store_model` models the table, statement
# semantics and a failure at the statement; `Vela_share_policy_send_store_lemmas`
# proves, for every starting database and every fault point, that each
# observation reports exactly what the run did to `sends`, and the store facts
# the send-link driver relies on.
#
# Needs `proofs/fstar/extraction-store` (regenerated by
# verify-fstar-share-executors.sh, which runs first in verify-fstar.sh) and the
# driver extraction.

proof_root=$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)
cd "$proof_root"

for command_name in cargo cargo-hax driver-hax-frontend-exporter hax-engine fstar.exe z3-4.13.3 jq; do
  command -v "$command_name" >/dev/null || {
    echo "$command_name is missing; follow ../vela-rekey-policy/README.md" >&2
    exit 1
  }
done

[[ $(fstar.exe --version | head -n1) == 'F* 2025.10.06' ]] || {
  echo 'unexpected F* version' >&2
  exit 2
}
[[ -f proofs/fstar/extraction-driver/Vela_share_policy.Driver.fst ]] || {
  echo 'run verify-fstar-driver.sh first' >&2
  exit 1
}
[[ -f proofs/fstar/extraction-store/Vela_share_policy.Store.fst ]] || {
  echo 'run verify-fstar-share-executors.sh first' >&2
  exit 1
}

# Rendering pins and the Rust mirror's shared vectors.
cargo test --lib send

generated=(proofs/fstar/extraction-store/Vela_share_policy.Store.fst)
driver=(proofs/fstar/extraction-driver/*.fst)
send_driver=(proofs/fstar/extraction-send-driver/Vela_share_policy.Send_driver.fst)
model=(proofs/fstar/store-lemmas/Vela_share_policy_store_model.fst)
share_lemmas=(proofs/fstar/store-lemmas/Vela_share_policy_store_lemmas.fst)
lemmas=(proofs/fstar/send-store-lemmas/Vela_share_policy_send_store_lemmas.fst)
for f in "${generated[@]}" "${send_driver[@]}" "${model[@]}" "${share_lemmas[@]}" "${lemmas[@]}"; do
  [[ -f $f ]] || { echo "missing $f" >&2; exit 1; }
done

python3 "$proof_root/../../security/formal/check-driver-proof-sources.py" \
  --generated "${generated[@]}" "${driver[@]}" "${send_driver[@]}" \
  --proof "${model[@]}" "${share_lemmas[@]}" "${lemmas[@]}" \
  --include-dir "$proof_root"

hax_lib_root=$(
  cargo metadata --format-version 1 |
    jq -r '.packages[] | select(.name == "hax-lib") | .manifest_path | sub("/Cargo.toml$"; "")'
)
[[ -n $hax_lib_root && -d $hax_lib_root ]] || {
  echo "could not locate hax-lib proof libraries" >&2
  exit 1
}

fstar_args=(
  --cmi
  --cache_off
  --warn_error -331
  --z3rlimit 200
  --z3version 4.13.3
  --already_cached '+Prims+FStar+LowStar+C+Spec.Loops+TestLib'
  --include "$hax_lib_root/proof-libs/fstar/core"
  --include "$hax_lib_root/proof-libs/fstar/rust_primitives"
  --include "$hax_lib_root/proofs/fstar/extraction"
  --include proofs/fstar/extraction-driver
  --include proofs/fstar/extraction-send-driver
  --include proofs/fstar/extraction-store
  --include proofs/fstar/store-lemmas
  --include proofs/fstar/send-store-lemmas
)
# One module at a time, each in its own process, so each stays within its
# memory budget.
for module in "${generated[@]}" "${model[@]}" "${lemmas[@]}"; do
  echo "checking $module"
  if [[ -x /usr/bin/time ]]; then
    /usr/bin/time -f "$module: %M KB peak, %e s" fstar.exe "${fstar_args[@]}" "$module"
  else
    fstar.exe "${fstar_args[@]}" "$module"
  fi
done

# Each mutant of the plans and classifiers must break the proof.
"$proof_root/verify-fstar-send-executors-mutations.sh"

echo "send executors: for every starting database and every failing statement, each one-off share-link executor's observation reports exactly what its statement did to sends, and a failed run leaves the table unchanged"
sha256sum "${generated[@]}" "${send_driver[@]}" "${model[@]}" "${share_lemmas[@]}" "${lemmas[@]}" src/store.rs src/store_model.rs
