#!/usr/bin/env bash
set -euo pipefail

# Handler-to-driver link for the one-off share-link endpoints.
#
# `src/send_interpreter.rs` defines the `send_interpreter!` loop once. Each
# server handler expands it with `.await`; this crate expands it into the
# synchronous `run_send`, which hax extracts here. The lemma module proves, for
# every executor, that `run_send` calls exactly the executor method for the
# effect the driver just emitted, stops at the verdict, reaches a verdict
# within its budget, and ends in the driver state the per-request send theorems
# cover.
#
# The driver module itself is taken from `extraction-send-driver`
# (regenerated by verify-fstar-send-driver.sh, which runs first); this
# extraction keeps only the interpreter module.

proof_root=$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)
cd "$proof_root"

for command_name in cargo cargo-hax driver-hax-frontend-exporter hax-engine fstar.exe z3-4.13.3 jq; do
  command -v "$command_name" >/dev/null || {
    echo "$command_name is missing; follow README.md" >&2
    exit 1
  }
done

[[ $(fstar.exe --version | head -n1) == 'F* 2025.10.06' ]] || {
  echo 'unexpected F* version' >&2
  exit 2
}
[[ -f proofs/fstar/extraction-send-driver/Vela_share_policy.Send_driver.fst ]] || {
  echo 'run verify-fstar-send-driver.sh first' >&2
  exit 1
}

cargo test --lib send_interpreter

rm -rf proofs/fstar/extraction-send-interpreter
cargo hax into \
  --output-dir proofs/fstar/extraction-send-interpreter \
  -i '-** +vela_share_policy::send_interpreter::** +vela_share_policy::send_driver::step' \
  fstar --z3rlimit 500
# The partial driver and root modules hax writes alongside are superseded by
# the full send-driver extraction.
rm -f proofs/fstar/extraction-send-interpreter/Vela_share_policy.Send_driver.fst
rm -f proofs/fstar/extraction-send-interpreter/Vela_share_policy.fst

generated=(proofs/fstar/extraction-send-interpreter/Vela_share_policy.Send_interpreter.fst)
driver=(proofs/fstar/extraction-send-driver/*.fst)
driver_lemmas=(proofs/fstar/send-driver-lemmas/Vela_share_policy_send_driver_lemmas.fst)
lemmas=(proofs/fstar/send-interpreter-lemmas/Vela_share_policy_send_interpreter_lemmas.fst)
for f in "${generated[@]}" "${lemmas[@]}"; do
  [[ -f $f ]] || { echo "missing $f" >&2; exit 1; }
done

python3 "$proof_root/../../security/formal/check-driver-proof-sources.py" \
  --generated "${generated[@]}" "${driver[@]}" \
  --proof "${driver_lemmas[@]}" "${lemmas[@]}" \
  --include-dir "$proof_root"

hax_lib_root=$(
  cargo metadata --format-version 1 |
    jq -r '.packages[] | select(.name == "hax-lib") | .manifest_path | sub("/Cargo.toml$"; "")'
)
[[ -n $hax_lib_root && -d $hax_lib_root ]] || {
  echo "could not locate hax-lib proof libraries" >&2
  exit 1
}

fstar_args=(
  --cmi
  --cache_off
  --warn_error -331
  --z3rlimit 8000
  --z3version 4.13.3
  --already_cached '+Prims+FStar+LowStar+C+Spec.Loops+TestLib'
  --include "$hax_lib_root/proof-libs/fstar/core"
  --include "$hax_lib_root/proof-libs/fstar/rust_primitives"
  --include "$hax_lib_root/proofs/fstar/extraction"
  --include proofs/fstar/extraction-send-driver
  --include proofs/fstar/send-driver-lemmas
  --include proofs/fstar/extraction-send-interpreter
  --include proofs/fstar/send-interpreter-lemmas
  "${generated[@]}" "${lemmas[@]}"
)
fstar.exe "${fstar_args[@]}"

echo "share-link interpreter: each handler's loop calls only the executor method for the driver's current effect, stops at the verdict within 3 turns, and ends in the driver state the per-request send theorems cover"
sha256sum "${generated[@]}" "${lemmas[@]}" src/send_interpreter.rs
