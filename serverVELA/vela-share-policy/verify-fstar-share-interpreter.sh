#!/usr/bin/env bash
set -euo pipefail

# Handler-to-driver link for the sharing endpoints.
#
# `src/interpreter.rs` defines the `share_interpreter!` loop once. The server's
# handlers expand it with `.await`; this crate expands it into the synchronous
# `run_share`, which hax extracts here. The lemma module proves, for every
# executor, that `run_share` calls exactly the executor method for the effect
# the driver just emitted, stops at the verdict, reaches a verdict within its
# budget, and ends in the driver state the per-request sharing theorems cover.
#
# The driver module itself is taken from `extraction-driver` (regenerated by
# verify-fstar-driver.sh, which runs first); this extraction keeps only the
# interpreter module.

proof_root=$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)
cd "$proof_root"

for command_name in cargo cargo-hax driver-hax-frontend-exporter hax-engine fstar.exe z3-4.13.3 jq; do
  command -v "$command_name" >/dev/null || {
    echo "$command_name is missing; follow ../vela-rekey-policy/README.md" >&2
    exit 1
  }
done

[[ $(fstar.exe --version | head -n1) == 'F* 2025.10.06' ]] || {
  echo 'unexpected F* version' >&2
  exit 2
}
[[ -f proofs/fstar/extraction-driver/Vela_share_policy.Driver.fst ]] || {
  echo 'run verify-fstar-driver.sh first' >&2
  exit 1
}

cargo test --lib interpreter

rm -rf proofs/fstar/extraction-interpreter
cargo hax into \
  --output-dir proofs/fstar/extraction-interpreter \
  -i '-** +vela_share_policy::interpreter::** +vela_share_policy::driver::step' \
  fstar --z3rlimit 500
# The partial driver and root modules hax writes alongside are superseded by
# the full driver extraction.
rm -f proofs/fstar/extraction-interpreter/Vela_share_policy.Driver.fst
rm -f proofs/fstar/extraction-interpreter/Vela_share_policy.fst

generated=(proofs/fstar/extraction-interpreter/Vela_share_policy.Interpreter.fst)
driver=(proofs/fstar/extraction-driver/*.fst)
driver_lemmas=(proofs/fstar/driver-lemmas/Vela_share_policy_driver_lemmas.fst)
lemmas=(proofs/fstar/interpreter-lemmas/Vela_share_policy_interpreter_lemmas.fst)
for f in "${generated[@]}" "${lemmas[@]}"; do
  [[ -f $f ]] || { echo "missing $f" >&2; exit 1; }
done

python3 "$proof_root/../../security/formal/check-driver-proof-sources.py" \
  --generated "${generated[@]}" "${driver[@]}" \
  --proof "${driver_lemmas[@]}" "${lemmas[@]}" \
  --include-dir "$proof_root"

hax_lib_root=$(
  cargo metadata --format-version 1 |
    jq -r '.packages[] | select(.name == "hax-lib") | .manifest_path | sub("/Cargo.toml$"; "")'
)
[[ -n $hax_lib_root && -d $hax_lib_root ]] || {
  echo "could not locate hax-lib proof libraries" >&2
  exit 1
}

fstar_args=(
  --cmi
  --cache_off
  --warn_error -331
  --z3rlimit 8000
  --z3version 4.13.3
  --already_cached '+Prims+FStar+LowStar+C+Spec.Loops+TestLib'
  --include "$hax_lib_root/proof-libs/fstar/core"
  --include "$hax_lib_root/proof-libs/fstar/rust_primitives"
  --include "$hax_lib_root/proofs/fstar/extraction"
  --include proofs/fstar/extraction-driver
  --include proofs/fstar/driver-lemmas
  --include proofs/fstar/extraction-interpreter
  --include proofs/fstar/interpreter-lemmas
  "${generated[@]}" "${lemmas[@]}"
)
fstar.exe "${fstar_args[@]}"

echo "share interpreter: the handler's loop calls only the executor method for the driver's current effect, stops at the verdict within 3 turns, and ends in the driver state the per-request sharing theorems cover"
sha256sum "${generated[@]}" "${lemmas[@]}" src/interpreter.rs
